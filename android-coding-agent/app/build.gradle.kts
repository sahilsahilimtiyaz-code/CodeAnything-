// Bundle the compiled extracted-intelligence service into APK assets so
// RuntimeManager can stage it inside Alpine at /intelligence.
// Build it first: (cd ../../extracted-intelligence && npm run build)
// Missing dist is non-fatal: the app falls back to a stub server.
val syncIntelligenceAssets = tasks.register<Sync>("syncIntelligenceAssets") {
    val intelDist = layout.projectDirectory.dir("../../extracted-intelligence/dist")
    from(intelDist)
    into(layout.projectDirectory.dir("src/main/assets/intelligence"))
    includeEmptyDirs = false
    onlyIf { intelDist.asFile.exists() }
}
tasks.matching { it.name.startsWith("merge") && it.name.contains("Assets") }.configureEach {
    dependsOn(syncIntelligenceAssets)
}
